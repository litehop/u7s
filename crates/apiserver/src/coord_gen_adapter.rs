    // ---- Byte-identical audit: codegen migration (Phase 4.10) ----
    //
    // Reconstructs the pre-migration hand-written `decode_lease_proto_gen_a`/
    // `decode_leasecandidate_proto_gen` verbatim (they called the exact same
    // `gen_object_meta_to_json`/`gen_microtime_to_rfc3339` helpers this migration left
    // untouched) and diffs their output against the codegen-generated `gen_lease_to_json`/
    // `gen_leasecandidate_to_json` this migration installed. A wrong field name, a missing
    // `!= 0` guard on `leaseDurationSeconds`/`leaseTransitions`, or a dropped MicroTime delegate
    // in `build/codegen.rs` would show up here as a JSON mismatch — leader election silently
    // misreading a lease's holder/renewal state is exactly the failure mode a byte-for-byte diff
    // against the known-good pre-migration output catches.
    #[test]
    fn codegen_migration_lease_family_matches_pre_migration_hand_written_output() {
        fn old_decode_lease_proto_gen_a(data: &[u8]) -> Option<serde_json::Value> {
            let lease = coord_v1::Lease::decode(data).ok()?;
            let meta = gen_object_meta_to_json(lease.metadata.unwrap_or_default());

            let mut obj = serde_json::json!({
                "apiVersion": "coordination.k8s.io/v1",
                "kind": "Lease",
                "metadata": meta
            });

            if let Some(spec) = lease.spec {
                let mut spec_map = serde_json::Map::new();
                if let Some(v) = spec.holder_identity.filter(|s| !s.is_empty()) {
                    spec_map.insert("holderIdentity".to_string(), serde_json::Value::String(v));
                }
                if let Some(v) = spec.lease_duration_seconds.filter(|&n| n != 0) {
                    spec_map.insert(
                        "leaseDurationSeconds".to_string(),
                        serde_json::Value::Number(v.into()),
                    );
                }
                if let Some(t) = spec.acquire_time.as_ref() {
                    if let Some(ts) = gen_microtime_to_rfc3339(t) {
                        spec_map.insert("acquireTime".to_string(), serde_json::Value::String(ts));
                    }
                }
                if let Some(t) = spec.renew_time.as_ref() {
                    if let Some(ts) = gen_microtime_to_rfc3339(t) {
                        spec_map.insert("renewTime".to_string(), serde_json::Value::String(ts));
                    }
                }
                if let Some(v) = spec.lease_transitions.filter(|&n| n != 0) {
                    spec_map.insert(
                        "leaseTransitions".to_string(),
                        serde_json::Value::Number(v.into()),
                    );
                }
                if let Some(v) = spec.strategy.filter(|s| !s.is_empty()) {
                    spec_map.insert("strategy".to_string(), serde_json::Value::String(v));
                }
                if let Some(v) = spec.preferred_holder.filter(|s| !s.is_empty()) {
                    spec_map.insert("preferredHolder".to_string(), serde_json::Value::String(v));
                }
                if !spec_map.is_empty() {
                    obj["spec"] = serde_json::Value::Object(spec_map);
                }
            }

            Some(obj)
        }

        fn old_decode_leasecandidate_proto_gen(data: &[u8]) -> Option<serde_json::Value> {
            let candidate = coord_v1alpha2::LeaseCandidate::decode(data).ok()?;
            let meta = gen_object_meta_to_json(candidate.metadata.unwrap_or_default());

            let mut obj = serde_json::json!({
                "apiVersion": "coordination.k8s.io/v1alpha2",
                "kind": "LeaseCandidate",
                "metadata": meta
            });

            if let Some(spec) = candidate.spec {
                let mut spec_map = serde_json::Map::new();
                if let Some(v) = spec.lease_name.filter(|s| !s.is_empty()) {
                    spec_map.insert("leaseName".to_string(), serde_json::Value::String(v));
                }
                if let Some(t) = spec.ping_time.as_ref() {
                    if let Some(ts) = gen_microtime_to_rfc3339(t) {
                        spec_map.insert("pingTime".to_string(), serde_json::Value::String(ts));
                    }
                }
                if let Some(t) = spec.renew_time.as_ref() {
                    if let Some(ts) = gen_microtime_to_rfc3339(t) {
                        spec_map.insert("renewTime".to_string(), serde_json::Value::String(ts));
                    }
                }
                if let Some(v) = spec.binary_version.filter(|s| !s.is_empty()) {
                    spec_map.insert("binaryVersion".to_string(), serde_json::Value::String(v));
                }
                if let Some(v) = spec.emulation_version.filter(|s| !s.is_empty()) {
                    spec_map.insert("emulationVersion".to_string(), serde_json::Value::String(v));
                }
                if let Some(v) = spec.strategy.filter(|s| !s.is_empty()) {
                    spec_map.insert("strategy".to_string(), serde_json::Value::String(v));
                }
                if !spec_map.is_empty() {
                    obj["spec"] = serde_json::Value::Object(spec_map);
                }
            }

            Some(obj)
        }

        // Every field set to a value no zero/empty-elision check could mistake for "unset"
        // (Sentinel's own contract), so the audit exercises `leaseDurationSeconds`/
        // `leaseTransitions`'s `!= 0` guards and both MicroTime fields' RFC3339 delegate, not
        // just the plain-string fields a less thorough fixture would happen to cover.
        let lease = coord_v1::Lease {
            metadata: Some(meta_v1::ObjectMeta {
                name: Some("audit-lease".to_string()),
                namespace: Some("kube-system".to_string()),
                ..Default::default()
            }),
            spec: Some(coord_v1::LeaseSpec::sentinel()),
        };
        let mut lease_bytes = Vec::new();
        lease.encode(&mut lease_bytes).unwrap();
        assert_eq!(
            old_decode_lease_proto_gen_a(&lease_bytes),
            decode_lease_proto_gen_a(&lease_bytes),
            "codegen-generated decode_lease_proto_gen_a must match the pre-migration \
             hand-written decoder field-for-field — any divergence here is a silent \
             leader-election-observable field drop introduced by the Phase 4.10 migration"
        );

        // A Lease with a present-but-all-zero/empty spec must still omit the `spec` key
        // entirely (not `spec: {{}}`) — the pre-migration decoder's own `!spec_map.is_empty()`
        // guard, which the generated `gen_lease_spec_to_json`/`lease_delegated_field`'s `spec`
        // entry must replicate rather than just mechanically inserting `Some(LeaseSpec::default())`.
        let empty_spec_lease = coord_v1::Lease {
            metadata: Some(meta_v1::ObjectMeta::default()),
            spec: Some(coord_v1::LeaseSpec::default()),
        };
        let mut empty_spec_bytes = Vec::new();
        empty_spec_lease.encode(&mut empty_spec_bytes).unwrap();
        assert_eq!(
            old_decode_lease_proto_gen_a(&empty_spec_bytes),
            decode_lease_proto_gen_a(&empty_spec_bytes),
            "a Lease with a present-but-empty LeaseSpec must still omit `spec` entirely, \
             matching the pre-migration decoder exactly"
        );

        let candidate = coord_v1alpha2::LeaseCandidate {
            metadata: Some(meta_v1::ObjectMeta {
                name: Some("audit-candidate".to_string()),
                namespace: Some("kube-system".to_string()),
                ..Default::default()
            }),
            spec: Some(coord_v1alpha2::LeaseCandidateSpec::sentinel()),
        };
        let mut candidate_bytes = Vec::new();
        candidate.encode(&mut candidate_bytes).unwrap();
        assert_eq!(
            old_decode_leasecandidate_proto_gen(&candidate_bytes),
            decode_leasecandidate_proto_gen(&candidate_bytes),
            "codegen-generated decode_leasecandidate_proto_gen must match the pre-migration \
             hand-written decoder field-for-field"
        );
    }
