// ---- shared helpers --------------------------------------------------------

fn gen_microtime_to_rfc3339(t: &meta_v1::MicroTime) -> Option<String> {
    Some(crate::core_gen_adapter::gen_microtime_fields_to_rfc3339(
        t.seconds?,
        t.nanos.unwrap_or(0),
    ))
}

fn gen_object_meta_to_json(meta: meta_v1::ObjectMeta) -> serde_json::Value {
    crate::core_gen_adapter::gen_object_meta_to_json(meta)
}

// ---- Adapter A: hand-written struct→JSON map, mirrors decode_lease_proto ----
//
// Fed by the prost-build-GENERATED Lease struct instead of the hand struct.
// Preserves the same omit-if-zero / omit-if-empty semantics as the original.
// Additionally emits strategy/preferredHolder which the original skipped.

// `gen_lease_spec_to_json`/`gen_lease_to_json` are generated by `build/codegen.rs` from the
// `.k8s.io.api.coordination.v1.LeaseSpec`/`.k8s.io.api.coordination.v1.Lease` descriptors —
// `leaseDurationSeconds`/`leaseTransitions` only emit once non-zero and `acquireTime`/`renewTime`
// delegate to the hand-written `gen_microtime_to_rfc3339` above; `metadata` delegates to
// `gen_object_meta_to_json` and `spec` delegates wholesale to `gen_lease_spec_to_json`; see
// `build/codegen.rs::lease_spec_delegated_field`/`lease_delegated_field`.
include!(concat!(env!("OUT_DIR"), "/lease_spec_gen.rs"));
include!(concat!(env!("OUT_DIR"), "/lease_gen.rs"));

pub fn decode_lease_proto_gen_a(data: &[u8]) -> Option<serde_json::Value> {
    let lease = coord_v1::Lease::decode(data).ok()?;
    let mut obj = gen_lease_to_json(lease);
    obj["apiVersion"] = "coordination.k8s.io/v1".into();
    obj["kind"] = "Lease".into();
    Some(obj)
}

// ---- LeaseCandidate (coordination.k8s.io/v1alpha2) ----
//
// CoordinatedLeaderElection candidates: namespaced, spec-only (no /status subresource — see
// upstream types.go, which declares no Status field on this type at all).

// `gen_leasecandidate_spec_to_json`/`gen_leasecandidate_to_json` are generated by
// `build/codegen.rs` from the `.k8s.io.api.coordination.v1alpha2.LeaseCandidateSpec`/
// `.k8s.io.api.coordination.v1alpha2.LeaseCandidate` descriptors — `pingTime`/`renewTime`
// delegate to the hand-written `gen_microtime_to_rfc3339` above; `metadata` delegates to
// `gen_object_meta_to_json` and `spec` delegates wholesale to `gen_leasecandidate_spec_to_json`;
// see `build/codegen.rs::leasecandidate_spec_delegated_field`/`leasecandidate_delegated_field`.
include!(concat!(env!("OUT_DIR"), "/leasecandidate_spec_gen.rs"));
include!(concat!(env!("OUT_DIR"), "/leasecandidate_gen.rs"));

pub fn decode_leasecandidate_proto_gen(data: &[u8]) -> Option<serde_json::Value> {
    let candidate = coord_v1alpha2::LeaseCandidate::decode(data).ok()?;
    let mut obj = gen_leasecandidate_to_json(candidate);
    obj["apiVersion"] = "coordination.k8s.io/v1alpha2".into();
    obj["kind"] = "LeaseCandidate".into();
    Some(obj)
}

